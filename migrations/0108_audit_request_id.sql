-- 0108 — request-id سراسری (ف۵ طرح ارتقا — P2-13): ستون request_id روی audit_log
-- زمینه: طرح §۴ آیتم ۱۳ — «شناسهٔ همبستگی بین لاگ/audit یک درخواست؛ دیباگ رویدادهای زنجیره‌ای ساده می‌شود».
-- هر درخواست /api/* یک شناسهٔ «req-<uuid>» می‌گیرد که در هدر پاسخ X-Request-Id، پاکت خطای JSON
-- (فیلد request_id) و ردیف‌های audit_logِ همان درخواست می‌نشیند؛ صدا زدن audit بیرون زمینهٔ
-- درخواست (کرون/فرصت‌طلب) ستون را null می‌گذارد — عمداً، چون آن رویدادها درخواستی ندارند.
-- الگوی افزودن ستون همان 0106 است: فقط-افزودنی، nullable، بدون بازسازی جدول.
-- بدون ایندکس: جست‌وجو با request_id فقط پرس‌وجوی عملیاتیِ کمیاب است و جدول با نگه‌داری
-- ۱۸۰روزه (ف۴) سقف‌دار می‌ماند؛ هزینهٔ ایندکس روی داغ‌ترین مسیر نوشتن سامانه توجیه ندارد.

ALTER TABLE audit_log ADD COLUMN request_id TEXT;
