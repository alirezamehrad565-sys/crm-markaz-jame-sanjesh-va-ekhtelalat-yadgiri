-- 0032 — (0.49.0): «پذیرش = خروج از لیست انتظار»
-- از این نسخه ورودیِ پذیرش‌شده (اولین جلسهٔ واقعی) با soft delete از صف بیرون می‌رود.
-- این مایگریشن همان قاعده را روی ورودی‌های admitted قدیمی اعمال می‌کند تا
-- لیست انتظارِ زنده فقط پشت‌نوبتی‌های واقعی را نشان دهد (تاریخچه در audit می‌ماند).
UPDATE waitlist
   SET deleted_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now'),
       updated_at = datetime('now')
 WHERE status = 'admitted'
   AND deleted_at IS NULL;
