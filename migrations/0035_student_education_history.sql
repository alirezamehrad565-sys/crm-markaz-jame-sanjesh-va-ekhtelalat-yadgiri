-- (0.54.0) — تاریخچهٔ تحصیلی دانش‌آموز
-- دستور کاربر: «دانش آموز از سال های قبل اومده باید یه حالت تاریخچه تحصیلی
-- داشته باشه که کجا درس خونده دانش اموز سطحش اون سال چی بوده توضیحات —
-- یه فرمی که بشه هی اطلاعات سال اضافه کرد»
-- جدول:
-- student_education_history رکورد سال‌به‌سال سابقهٔ تحصیلی (به‌خصوص پرونده‌های
-- آرشیو که از سال‌های قبل می‌آیند): سال تحصیلی،
-- مدرسه/آموزشگاه، سطح/پایهٔ همان سال، توضیحات
-- قراردادها:
-- - بدون CHECK در SQL (الگوی D7 — محدودیت‌ها با Zod در کد)
-- - ON DELETE CASCADE: حذف کامل پروندهٔ بی‌سابقه نباید به‌خاطر
-- سابقهٔ تحصیلی بلاک شود — تاریخچه جزء خود پرونده است
-- - school_name متن آزاد است (نه FK به schools): دانش‌آموز ممکن است در
-- مدارس خارج از سامانه (شهرستان/مدارس قبلی) درس خوانده باشد
-- - created_by اختیاری: ثبت دستی دفتر؛ نگه‌داشتن ردپای همکار ثبت‌کننده
-- ============================================================

CREATE TABLE IF NOT EXISTS student_education_history (
  id          TEXT PRIMARY KEY,
  student_id  TEXT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  study_year  TEXT NOT NULL,             -- سال تحصیلی آزاد: «۱۴۰۲–۱۴۰۳» یا «سال دوم»
  school_name TEXT,                      -- کجا درس خوانده (متن آزاد)
  level       TEXT,                      -- سطح/پایهٔ دانش‌آموز در همان سال
  notes       TEXT,                      -- توضیحات آزاد
  created_by  TEXT REFERENCES staff(id),
  created_at  TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_edu_hist_student ON student_education_history(student_id, created_at);
