-- 0113 — rust-f15: شمارش مصرف روزانهٔ سهمیهٔ مرکز (docs/rust/node-sync.md §سهمیه)
-- چرا جدول جدا؟ سهمیهٔ روزانهٔ Cloudflare (Workers/D1 پلن رایگان) پلتفورمی است و D1 خودش
-- شمارش درخواست/ردیف نمی‌دهد؛ پس مرکز خودش «برآورد مصرف» را در یک ردیف به‌ازای هر روز UTC
-- انبار می‌کند تا GET /api/central/quota بتواند سطح مصرف (ok/warn/danger) را اعلام کند.
-- دانه‌بندی: PRIMARY KEY(day) — یک ردیف به‌ازای هر روز UTC؛ شمارش با UPSERT تک‌دستوری
-- (INSERT ... ON CONFLICT(day) DO UPDATE) جمع می‌شود — هم‌ریتم upsertهای idempotent مخزن.
-- چه چیزی شمرده می‌شود؟ فقط سه مسیر پرهزینهٔ واقعی: pull نود، push نود، تلاش ورود (موفق/ناموفق).
-- خواندنی‌های مدیریتی (پنل/گزارش‌ها) عمداً شمرده نمی‌شوند — برآورد باید نزدیک هزینهٔ واقعی
-- بماند و با شمارش نویز، اعتبارش را از دست بدهد.
-- برآوردی بودن: مقادیر rows_written/rows_read_est «تخمین ثابت هر هندلر» هستند (ثابت‌های
-- نام‌دار در src/node-sync/service.ts) نه شمارش دقیق — هدف هشدار زودهنگام است نه صورتحساب.
-- فقط-افزودنی (additive-only): هیچ جدول موجودی دست نمی‌خورد؛ بدون CHECK (الگوی D7) و
-- بدون ایندکس اضافه — کلید اصلی day کافی است و هرس ردیف‌های کهنه بعداً تصمیم جدا دارد.

CREATE TABLE IF NOT EXISTS quota_usage (
  day           TEXT PRIMARY KEY,          -- روز UTC به شکل YYYY-MM-DD
  requests      INTEGER NOT NULL,          -- شمار درخواست‌های شمرده‌شدهٔ همان روز
  rows_written  INTEGER NOT NULL,          -- برآورد ردیف‌نویسی همان روز
  rows_read_est INTEGER NOT NULL           -- برآورد ردیف‌خوانی همان روز (est = estimated)
);
