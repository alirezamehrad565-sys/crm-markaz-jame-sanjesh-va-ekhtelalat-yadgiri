-- ─── فهرست مرجع مهارت‌ها — حیطهٔ ۱: حرکات درشت ───
CREATE TABLE IF NOT EXISTS ot_skills (
  id        TEXT PRIMARY KEY,
  domain    TEXT NOT NULL,   -- gross|fine|visual|auditory|cognitive|adl|social
  ord       INTEGER NOT NULL, -- ترتیب سختی داخل حیطه (۱ = ساده‌ترین)
  title     TEXT NOT NULL,
  criterion TEXT NOT NULL    -- معیار قبولی — نمره‌دهی یکسان بین درمانگرها
);

CREATE INDEX IF NOT EXISTS idx_ot_skills_domain ON ot_skills(domain, ord);

CREATE TABLE IF NOT EXISTS ot_progress (
  id             TEXT PRIMARY KEY,
  student_id     TEXT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  skill_id       TEXT NOT NULL REFERENCES ot_skills(id) ON DELETE CASCADE,
  status         TEXT NOT NULL,   -- mastered|with_help|not_yet — ماتریس در کد
  note           TEXT,            -- یادداشت مهارت (سقف ۳۰۰ — کد)
  session_id     TEXT,            -- بند ردیف‌های یک جلسه
  appointment_id TEXT REFERENCES appointments(id),
  staff_id       TEXT REFERENCES staff(id),
  occurred_at    TEXT NOT NULL,   -- ISO UTC
  created_at     TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_ot_progress_student ON ot_progress(student_id, skill_id, occurred_at);

