-- نوع 'trail' در کد از رجیستری حذف شده و gameKindOf('trail') به گونوگو برمی‌گردد؛
-- ردیف‌های تاریخی game_packages با kind='trail' در DB می‌مانند (CHECK دیتابیس سالم است).

