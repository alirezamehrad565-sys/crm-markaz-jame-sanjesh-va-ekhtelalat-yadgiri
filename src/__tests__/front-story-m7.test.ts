/**
 * POLISH-3 M7 — گیت برچسب داستان «این برای کدام تصمیم است» (۱.۲۷.۳۰)
 *
 * هر کارتِ نیمه‌داستانِ باقی‌مانده یک زیرنویس یک‌خطی می‌گیرد که آزمون سه‌پرسشی را جواب می‌دهد:
 * برای کی؟ در چه لحظه‌ای؟ به کدام تصمیم؟ — الگو: کارت اعتبارسنجی بیرونی (M6).
 * ۱۶ کارت: ۶ داشبورد + ۱۰ گزارش (۶ گزارش مدیر + ۴ تحلیل پیشرفته) — دونات‌های بدون حفر هم داخل همین‌اند.
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(__dirname, '../..');
const read = (p: string) => readFileSync(join(ROOT, p), 'utf8');
const SUB = "class: 'hint-text', style: { flexBasis: '100%', margin: '0' }";

describe('POLISH-3 M7 — برچسب داستان کارت‌های باقی‌مانده', () => {
  test('الگوی مشترک زیرنویس (سطر دوم در card__head)', () => {
    const dash = read('public/assets/js/views/dashboard.js');
    const rep = read('public/assets/js/views/reports.js');
    // الگوی M6: hint-text با flexBasis کامل → زیر عنوان می‌نشیند
    expect(dash).toContain("class: 'hint-text', style: { flexBasis: '100%'");
    expect(rep).toContain("class: 'hint-text', style: { flexBasis: '100%'");
    expect(dash).toContain('M7 POLISH-3 (۱.۲۷.۳۰) — برچسب داستان: برای کی؟ در چه لحظه‌ای؟ به کدام تصمیم؟');
    expect(rep).toContain('M7 POLISH-3 (۱.۲۷.۳۰) — برچسب داستان: برای کی؟ در چه لحظه‌ای؟ به کدام تصمیم؟');
  });

  test('داشبورد — ۶ کارت برچسب داستان دارند', () => {
    const dash = read('public/assets/js/views/dashboard.js');
    const cards: [string, string][] = [
      ["'روند ۷ روز اخیر'", 'کدام روزها پر و کدام خالی بوده‌اند تا تصمیم ساعت‌بندی و ظرفیت جلسات روی داده گرفته شود'],
      ["'پیگیری‌های سررسیده'", 'چه کسی منتظر تماس مانده تا تصمیم پیگیریِ امروز پیش از سرد شدن خانواده گرفته شود'],
      ["'چه مدت در انتظارند؟'", 'چه کسی بیشترین انتظار را داشته تا تصمیم نوبت‌دهی عادلانه گرفته شود'],
      ["'اطلاع‌رسانی مرکز'", 'چه خبر تعطیلی یا تغییر برنامه اعلام شده تا تصمیم فردی دربارهٔ حضورشان درست باشد'],
      ["'دانش‌افزایی'", 'چه مطلب تازه‌ای منتشر شده تا تصمیم به‌روزرسانی دانش بالینی گرفته شود'],
      ["'سنجش روزانه — گزارش کوتاه'", 'چند غربال ثبت و چند مانده تا تصمیم ارجاع یا فراخوان بعدی گرفته شود']
    ];
    for (const [card, label] of cards) {
      expect(dash).toContain(card);
      expect(dash).toContain(label);
      // برچسب باید در همان کارت باشد — پس از عنوان، پیش از کارت بعدی
      const at = dash.indexOf(card);
      const after = dash.indexOf(label, at);
      expect(after).toBeGreaterThan(at);
    }
    expect(dash.split("class: 'hint-text', style: { flexBasis: '100%'").length - 1).toBe(6); // ۶ کارت M7 — کارت اعتبارسنجی M6 الگوی margin دارد
  });

  test('گزارش مدیر — ۶ کارت برچسب داستان دارند', () => {
    const rep = read('public/assets/js/views/reports.js');
    const cards: [string, string][] = [
      ["'روند روزانه نوبت‌ها'", 'کدام روزها اوج و افت دارند تا تصمیم ظرفیت و پذیرش تنظیم شود'],
      ["'وضعیت حضور دانش‌آموزان'", 'چه کسانی غیبت تکراری دارند تا تصمیم گفت‌وگو با خانواده گرفته شود'],
      ["'بار کاری همکاران'", 'بار هر همکار چند است تا تصمیم تقسیم کار عادلانه گرفته شود'],
      ["'مدارس مبدأ دانش‌آموزان'", 'از کدام مدارس مراجعه بیشتر است تا تصمیم همکاری با همان مدارس گرفته شود'],
      ["'پرتکرارترین دانش‌آموزان'", 'چه کسانی بیشترین مراجعه را دارند تا تصمیم ادامهٔ مسیر درمانشان گرفته شود'],
      ["'برچسب‌های پرتکرار'", 'کدام موضوعها تکرار می‌شوند تا تصمیم محتوای دانش‌افزایی گرفته شود']
    ];
    for (const [card, label] of cards) {
      expect(rep).toContain(card);
      expect(rep).toContain(label);
    }
  });

  test('تحلیل پیشرفته — ۴ کارت برچسب داستان دارند', () => {
    const rep = read('public/assets/js/views/reports.js');
    const cards: [string, string][] = [
      ["'شاخص‌های مرکز'", 'کدام شاخص افت کرده تا تصمیم اصلاحی دربارهٔ نوبت‌دهی و منابع گرفته شود'],
      ["'روند هفتگی جلسات'", 'رشد یا افت جلسات کجاست تا تصمیم برنامهٔ ظرفیت بعدی گرفته شود'],
      ["'قیف لیست انتظار — کل تاریخ'", 'خانواده‌ها در کدام مرحلهٔ قیف می‌مانند تا تصمیم بازکردن گلوگاه جذب گرفته شود'],
      ["'جزئیات هفته‌ها'", 'هر هفته چند فراخوان و پذیرش بوده تا تصمیم اقدام هفتهٔ بعد گرفته شود']
    ];
    for (const [card, label] of cards) {
      expect(rep).toContain(card);
      expect(rep).toContain(label);
    }
  });

  test('دونات‌های بدون حفرِ باقی‌مانده پوشش داده شدند', () => {
    const rep = read('public/assets/js/views/reports.js');
    // دونات حضور drill بورد روز را در M2 گرفت؛ دونات مدارس مبدأ و قیف با برچسب داستان M7 پوشش می‌گیرند
    expect(rep).toContain('از کدام مدارس مراجعه بیشتر است تا تصمیم همکاری با همان مدارس گرفته شود');
    expect(rep).toContain('خانواده‌ها در کدام مرحلهٔ قیف می‌مانند تا تصمیم بازکردن گلوگاه جذب گرفته شود');
  });
});
