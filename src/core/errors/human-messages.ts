/**
 * تبدیل نوع خطای ماشینی به پیام انسانی فارسی؛ متغیرهای {var} داخل متن با مقادیر داده‌شده
 * جانشین می‌شوند. نوع ناشناخته را عمداً با خطا رد می‌کنیم تا بوی خطای بی‌پیام به UI نرسد.
 */
export function humanizeError(kind: HumanErrorKind, vars?: Record<string, string | number>): HumanMessage {
  const template = HUMAN_MESSAGES[kind];
  if (!template) throw new Error(`برای این نوع خطا پیام انسانی تعریف نشده است: ${String(kind)}`);
  if (!vars) return template;
  const fill = (text: string): string =>
    text.replace(/\{(\w+)\}/g, (whole, key: string) => (Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : whole));
  return { title: fill(template.title), hint: fill(template.hint), action: fill(template.action) };
}
