// eval generated source in a fresh module-like scope (smoke test + internal use)
function loadRefFromSource(src) {
  const m = { exports: {} };
  new Function("module", "exports", src)(m, m.exports);
  if (typeof m.exports.formulateCase !== "function") throw new Error("reference smoke-test failed: formulateCase missing");
  return m.exports;
}

export function main() {
  const bundleSrc = readFileSync(BUNDLE_PATH, "utf8");
  const src = buildRefSource(bundleSrc);
  writeFileSync(REF_PATH, src);
  loadRefFromSource(src);
  console.log(`bundle-formulation-ref.cjs written (${src.split("\n").length} lines); smoke-test OK`);
}

const isCli = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (isCli) {
  main();
}
